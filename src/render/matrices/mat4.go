package matrices

import . "scop/src/render/vectors"

type Mat4 [4][4]float32
type Mat4x2 [4][2]float32
type Mat4x3 [4][3]float32

func (m Mat4) ToFlat() [4 * 4]float32 {
	return [4 * 4]float32{
		m[0][0], m[0][1], m[0][2], m[0][3],
		m[1][0], m[1][1], m[1][2], m[1][3],
		m[2][0], m[2][1], m[2][2], m[2][3],
		m[3][0], m[3][1], m[3][2], m[3][3],
	}
}

func (m Mat4x2) ToFlat() [4 * 2]float32 {
	return [4 * 2]float32{
		m[0][0], m[0][1],
		m[1][0], m[1][1],
		m[2][0], m[2][1],
		m[3][0], m[3][1],
	}
}

func (m Mat4x3) ToFlat() [4 * 3]float32 {
	return [4 * 3]float32{
		m[0][0], m[0][1], m[0][2],
		m[1][0], m[1][1], m[1][2],
		m[2][0], m[2][1], m[2][2],
		m[3][0], m[3][1], m[3][2],
	}
}

func (m Mat4) Add(rhs Mat4) Mat4 {
	return Mat4{
		{m[0][0] + rhs[0][0], m[0][1] + rhs[0][1], m[0][2] + rhs[0][2], m[0][3] + rhs[0][3]},
		{m[1][0] + rhs[1][0], m[1][1] + rhs[1][1], m[1][2] + rhs[1][2], m[1][3] + rhs[1][3]},
		{m[2][0] + rhs[2][0], m[2][1] + rhs[2][1], m[2][2] + rhs[2][2], m[2][3] + rhs[2][3]},
		{m[3][0] + rhs[3][0], m[3][1] + rhs[3][1], m[3][2] + rhs[3][2], m[3][3] + rhs[3][3]},
	}
}

